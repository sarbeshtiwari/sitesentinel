import { createHash, createHmac } from "node:crypto";

/**
 * Minimal S3 client (AWS Signature V4, path-style) for private artifact storage (Phase 4D).
 * Objects are never public: every request is signed with the service credentials; customers
 * receive artifacts only through the API's short-lived signed links.
 */
export interface S3Config { endpoint: string; region?: string; accessKey: string; secretKey: string; bucket: string }

const sha256 = (d: string | Buffer) => createHash("sha256").update(d).digest("hex");
const hmac = (k: string | Buffer, d: string) => createHmac("sha256", k).update(d).digest();
const enc = (s: string) => encodeURIComponent(s).replace(/[!'()*]/g, (c) => `%${c.charCodeAt(0).toString(16).toUpperCase()}`);

export class S3Error extends Error {
  constructor(readonly status: number, message: string) { super(message); }
}

/** Keys are generated by the platform only: safe characters, no traversal. */
export function assertKey(key: string): string {
  if (!/^[A-Za-z0-9][A-Za-z0-9/_.-]{0,500}$/.test(key) || key.includes("..") || key.includes("//")) throw new Error("invalid object key");
  return key;
}

export function createS3(cfg: S3Config) {
  const region = cfg.region ?? "us-east-1";
  const base = new URL(cfg.endpoint);

  async function send(method: string, key: string | null, body?: Buffer, headers: Record<string, string> = {}): Promise<Response> {
    const path = `/${enc(cfg.bucket)}${key !== null ? `/${assertKey(key).split("/").map(enc).join("/")}` : ""}`;
    const now = new Date();
    const amzDate = now.toISOString().replace(/[-:]/g, "").replace(/\.\d{3}/, "");
    const date = amzDate.slice(0, 8);
    const payloadHash = sha256(body ?? "");
    const h: Record<string, string> = { ...headers, host: base.host, "x-amz-date": amzDate, "x-amz-content-sha256": payloadHash };
    const names = Object.keys(h).map((k) => k.toLowerCase()).sort();
    const lower = Object.fromEntries(Object.entries(h).map(([k, v]) => [k.toLowerCase(), String(v).trim()]));
    const canonical = [method, path, "", names.map((n) => `${n}:${lower[n]}\n`).join(""), names.join(";"), payloadHash].join("\n");
    const scope = `${date}/${region}/s3/aws4_request`;
    const toSign = ["AWS4-HMAC-SHA256", amzDate, scope, sha256(canonical)].join("\n");
    const kSign = hmac(hmac(hmac(hmac(`AWS4${cfg.secretKey}`, date), region), "s3"), "aws4_request");
    const signature = createHmac("sha256", kSign).update(toSign).digest("hex");
    const auth = `AWS4-HMAC-SHA256 Credential=${cfg.accessKey}/${scope}, SignedHeaders=${names.join(";")}, Signature=${signature}`;
    const { host: _host, ...sendHeaders } = lower;
    return fetch(new URL(path, base), { method, headers: { ...sendHeaders, authorization: auth }, body: body ? new Uint8Array(body) : undefined, signal: AbortSignal.timeout(15_000) });
  }

  return {
    bucket: cfg.bucket,
    /** Phase 4H: reachability + credentials check for health reporting (HEAD bucket; no data read or written) */
    async ping() {
      const head = await send("HEAD", null);
      if (!head.ok) throw new S3Error(head.status, `bucket check failed (${head.status})`);
    },
    async ensureBucket() {
      const head = await send("HEAD", null);
      if (head.ok) return;
      const r = await send("PUT", null);
      if (!r.ok && r.status !== 409) throw new S3Error(r.status, `create bucket failed (${r.status})`);
    },
    async put(key: string, body: Buffer, contentType: string) {
      const r = await send("PUT", key, body, { "content-type": contentType });
      if (!r.ok) throw new S3Error(r.status, `put failed (${r.status})`);
    },
    async get(key: string): Promise<Buffer | null> {
      const r = await send("GET", key);
      if (r.status === 404) return null;
      if (!r.ok) throw new S3Error(r.status, `get failed (${r.status})`);
      return Buffer.from(await r.arrayBuffer());
    },
    async delete(key: string) {
      const r = await send("DELETE", key);
      if (!r.ok && r.status !== 404) throw new S3Error(r.status, `delete failed (${r.status})`);
    },
  };
}
export type S3 = ReturnType<typeof createS3>;
