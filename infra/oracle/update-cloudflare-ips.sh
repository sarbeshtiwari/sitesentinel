#!/usr/bin/env bash
# Refresh Cloudflare's edge ranges in nginx (set_real_ip_from) and the host firewall (80/443 allow-list).
# Weekly via sitesentinel-cf-ips.timer; safe to run by hand: sudo infra/oracle/update-cloudflare-ips.sh
# The nginx file is only replaced when the downloaded list looks sane, and nginx is reloaded only after `nginx -t`.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="${SITESENTINEL_DIR:-/opt/sitesentinel}"
# Live copy outside the git checkout (mounted into nginx); the repository file is only the initial snapshot.
CONF="$APP_DIR/cloudflare-realip.conf"
[ -f "$CONF" ] || cp "$HERE/nginx/cloudflare-realip.conf" "$CONF"
tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT

v4="$(curl -fsS --max-time 15 https://www.cloudflare.com/ips-v4)"
v6="$(curl -fsS --max-time 15 https://www.cloudflare.com/ips-v6)"
n4="$(printf '%s\n' "$v4" | grep -cE '^[0-9.]+/[0-9]+$' || true)"
n6="$(printf '%s\n' "$v6" | grep -cE '^[0-9a-f:]+/[0-9]+$' || true)"
if [ "$n4" -lt 10 ] || [ "$n6" -lt 3 ]; then echo "unexpected Cloudflare list ($n4 v4, $n6 v6); keeping the current one" >&2; exit 1; fi

{
  echo "# Cloudflare edge ranges (https://www.cloudflare.com/ips/). Generated by infra/oracle/update-cloudflare-ips.sh — do not edit."
  echo "# Snapshot: $(date -u +%Y-%m-%d)"
  printf '%s\n%s\n' "$v4" "$v6" | grep / | sed 's/.*/set_real_ip_from &;/'
} > "$tmp"

if ! cmp -s <(grep -v '^#' "$tmp") <(grep -v '^#' "$CONF" 2>/dev/null); then
  cp "$tmp" "$CONF"; chmod 644 "$CONF"
  echo "nginx real-IP ranges updated"
  if docker ps --format '{{.Names}}' | grep -qx 'sitesentinel-nginx-1'; then
    docker exec sitesentinel-nginx-1 nginx -t -q && docker exec sitesentinel-nginx-1 nginx -s reload && echo "nginx reloaded"
  fi
else
  echo "nginx real-IP ranges unchanged"
fi

if [ "$(id -u)" -eq 0 ]; then SITESENTINEL_DIR="$APP_DIR" "$HERE/firewall.sh"; else echo "not root: firewall not refreshed (sudo $HERE/firewall.sh)"; fi
