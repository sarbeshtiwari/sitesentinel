import { z } from "zod";
import {
  ALERT_RULES, billableUsage, type HealthState, OPERATIONAL_SECTIONS, resolveSettings, SETTINGS, settingMeta, settingsInSection, usageKeyDef,
} from "@wim/core";
import type { Db, Tx } from "@wim/db";
import {
  AdminAckInput, AdminAcceptDiscrepancyInput, AdminAdjustInput, AdminAlertQuery, AdminOpsHistoryQuery, AdminReconcileInput,
  AdminRetentionInput, AdminUsageQuery, Uuid,
} from "@wim/contracts";
import { platformVerdict } from "@wim/queue";
import { ADMIN_DB } from "../infra/infra.module.js";
import { Errors } from "../common/errors.js";
import { AdminApi, Client, CurrentAdmin, parse, RequireAdminPermission, type AdminContext, type ClientInfo } from "../common/context.js";
import { PLATFORM_STREAM } from "../audit/audit.service.js";

const n = (v: unknown) => (v === null || v === undefined ? null : Number(v));
const day = (d: Date) => d.toISOString().slice(0, 10);

/**
 * Phase 4H: platform operations for Super Admin — health, self-alerts, usage accounting and operational configuration.
 * Connects as wim_admin. Everything returned is operational or aggregate: worker identities, queue numbers, alert
 * reasons (generated by the evaluator from aggregates), and usage COUNTS per organisation. Never URLs, page content,
 * screenshots, incidents, credentials or customer telemetry (asserted by integration tests).
 */
@AdminApi()
@Controller("api/admin/v1/ops")
export class OpsController {
  constructor(@Inject(ADMIN_DB) private readonly db: Db) {}

  // ================================================================================================ health
  /** Evaluated component states + per-worker detail. Reads the snapshot only (no Redis / BullMQ calls per request). */
  @Get("health")
  @RequireAdminPermission("admin:monitoring:read")
  async health() {
    const [components, workers, alerts] = await Promise.all([
      this.db.platformHealth.findMany({ where: { component: { not: "__evaluator" } }, orderBy: { component: "asc" } }),
      this.db.workerHeartbeat.findMany({ orderBy: [{ kind: "asc" }, { workerId: "asc" }] }),
      this.db.platformAlert.groupBy({ by: ["severity", "state"], where: { state: { not: "RECOVERED" } }, _count: { _all: true } }),
    ]);
    const evaluator = await this.db.platformHealth.findUnique({ where: { component: "__evaluator" }, select: { evaluatedAt: true, evaluatedBy: true } });
    const settings = resolveSettings(await this.db.platformSetting.findMany({ where: { key: { startsWith: "ops." } } }));
    const now = Date.now();
    const staleSec = settings["ops.health.heartbeatStaleSec"];
    // the snapshot itself can be stale (no evaluator running): never present an old "healthy" as current
    const snapshotAgeSec = evaluator ? Math.round((now - evaluator.evaluatedAt.getTime()) / 1000) : null;
    const snapshotStale = snapshotAgeSec === null || snapshotAgeSec > settings["ops.health.evaluateEverySec"] * 3;
    return {
      data: {
        evaluatedAt: evaluator?.evaluatedAt.getTime() ? evaluator.evaluatedAt.toISOString() : null,
        evaluatedBy: evaluator?.evaluatedBy ?? null,
        snapshotAgeSec,
        snapshotStale,
        components: components.map((c) => ({
          component: c.component, state: snapshotStale ? "UNKNOWN" : c.state, lastEvaluatedState: c.state, reasons: c.reasons, metrics: c.metrics,
          since: c.since.toISOString(), evaluatedAt: c.evaluatedAt.toISOString(),
        })),
        workers: workers.map((w) => {
          const ageSec = Math.round((now - w.lastSeenAt.getTime()) / 1000);
          const deps = (w.deps ?? {}) as Record<string, { ok: boolean; ms?: number; at: string; error?: string }>;
          const alive = ageSec <= staleSec;
          return {
            workerId: w.workerId, kind: w.kind, version: w.version, startedAt: w.startedAt.toISOString(), lastSeenAt: w.lastSeenAt.toISOString(), heartbeatAgeSec: ageSec,
            alive, activeJobs: w.activeJobs, capacity: w.capacity, available: Math.max(0, w.capacity - w.activeJobs), processed: w.processed, failed: w.failed, timeouts: w.timeouts,
            lastJobAt: w.lastJobAt?.toISOString() ?? null, rssMb: w.rssMb, dependencies: deps, meta: w.meta ?? {},
            state: !alive ? "UNHEALTHY" : Object.values(deps).some((d) => !d.ok) ? "DEGRADED" : "HEALTHY",
          };
        }),
        openAlerts: alerts.map((a) => ({ severity: a.severity, state: a.state, count: a._count._all })),
        // release readiness: the PLATFORM verdict (is customer monitoring happening?), distinct from any single worker
        platform: snapshotStale ? { state: "UNKNOWN", customerMonitoring: "UNKNOWN", pipeline: "UNKNOWN", dependencies: "UNKNOWN" }
          : platformVerdict(components.map((c) => ({ component: c.component, state: c.state as HealthState }))),
      },
    };
  }

  /** State transitions and worker samples for a period (aggregate history; bounded to 7 days). */
  @Get("history")
  @RequireAdminPermission("admin:monitoring:read")
  async history(@Query() q: unknown) {
    const { hours } = parse(AdminOpsHistoryQuery, q);
    const [transitions, samples, starts] = await Promise.all([
      this.db.$queryRaw<Array<{ at: Date; component: string; from: string; to: string }>>`
        SELECT recorded_at AS at, labels->>'component' AS component, labels->>'from' AS "from", labels->>'to' AS "to"
          FROM system_health_logs WHERE component = 'ops' AND metric = 'state' AND recorded_at > now() - make_interval(hours => ${hours})
         ORDER BY recorded_at DESC LIMIT 500`,
      this.db.$queryRaw<Array<{ bucket: Date; kind: string; workers: number; active: number; capacity: number }>>`
        SELECT date_trunc('hour', recorded_at) + floor(extract(minute FROM recorded_at) / 10) * interval '10 minutes' AS bucket, labels->>'kind' AS kind,
               count(DISTINCT labels->>'worker')::int AS workers, round(avg(value))::int AS active, round(avg((labels->>'capacity')::int))::int AS capacity
          FROM system_health_logs WHERE component = 'worker' AND metric = 'sample' AND recorded_at > now() - make_interval(hours => ${hours})
         GROUP BY 1, 2 ORDER BY 1`,
      this.db.$queryRaw<Array<{ kind: string; n: number }>>`
        SELECT labels->>'kind' AS kind, count(*)::int AS n FROM system_health_logs
         WHERE component = 'worker' AND metric = 'start' AND recorded_at > now() - make_interval(hours => ${hours}) GROUP BY 1`,
    ]);
    return {
      data: {
        hours,
        transitions: transitions.map((t) => ({ ...t, at: t.at.toISOString() })),
        samples: samples.map((s) => ({ ...s, bucket: s.bucket.toISOString() })),
        restarts: starts,
      },
    };
  }

  // ================================================================================================ alerts
  @Get("alerts")
  @RequireAdminPermission("admin:monitoring:read")
  async alerts(@Query() q: unknown) {
    const { state, limit } = parse(AdminAlertQuery, q);
    const where = state === "ALL" ? {} : state === "ACTIVE" ? { state: { not: "RECOVERED" } } : { state };
    const rows = await this.db.platformAlert.findMany({ where, orderBy: [{ state: "asc" }, { lastSeenAt: "desc" }], take: limit });
    return { data: rows.map((a) => this.alertDto(a)) };
  }

  @Get("alerts/:alertId")
  @RequireAdminPermission("admin:monitoring:read")
  async alert(@Param("alertId") id: string) {
    const alertId = parse(Uuid, id);
    const a = await this.db.platformAlert.findUnique({ where: { id: alertId }, include: { events: { orderBy: { at: "asc" }, take: 500 } } });
    if (!a) throw Errors.notFound();
    return { data: { ...this.alertDto(a), events: a.events.map((e) => ({ id: String(e.id), at: e.at.toISOString(), type: e.type, actorId: e.actorId, details: e.details })) } };
  }

  /** Acknowledge: stops repeat notifications; the alert still recovers on its own. Audited. */
  @Post("alerts/:alertId/acknowledge")
  @HttpCode(200)
  @RequireAdminPermission("admin:ops:alerts")
  async acknowledge(@CurrentAdmin() admin: AdminContext, @Param("alertId") id: string, @Body() body: unknown, @Client() client: ClientInfo) {
    const alertId = parse(Uuid, id);
    const { reason } = parse(AdminAckInput, body);
    const a = await this.db.$transaction(async (tx) => {
      const r = await tx.platformAlert.updateMany({ where: { id: alertId, state: "OPEN" }, data: { state: "ACKNOWLEDGED", acknowledgedAt: new Date(), acknowledgedById: admin.adminId } });
      if (!r.count) {
        const exists = await tx.platformAlert.findUnique({ where: { id: alertId }, select: { state: true } });
        if (!exists) throw Errors.notFound();
        throw Errors.conflict(`Only open alerts can be acknowledged (this one is ${exists.state.toLowerCase()})`);
      }
      await tx.platformAlertEvent.create({ data: { alertId, type: "ACKNOWLEDGED", actorId: admin.adminId, details: { reason } } });
      await this.audit(tx, admin, client, "admin.platform_alert_acknowledged", "platform_alert", alertId, { to: "ACKNOWLEDGED" }, reason);
      return tx.platformAlert.findUniqueOrThrow({ where: { id: alertId } });
    });
    return { data: this.alertDto(a) };
  }

  private alertDto(a: { id: string; fingerprint: string; rule: string; component: string; severity: string; state: string; reason: string; details: unknown; openedAt: Date; lastSeenAt: Date; occurrences: number; reopenCount: number; acknowledgedAt: Date | null; acknowledgedById: string | null; recoveredAt: Date | null; suppressedBy: string | null; lastNotifiedAt: Date | null; notifyState: string }) {
    return {
      id: a.id, fingerprint: a.fingerprint, rule: a.rule, component: a.component, severity: a.severity, state: a.state, reason: a.reason, details: a.details,
      openedAt: a.openedAt.toISOString(), lastSeenAt: a.lastSeenAt.toISOString(), occurrences: a.occurrences, reopenCount: a.reopenCount,
      acknowledgedAt: a.acknowledgedAt?.toISOString() ?? null, acknowledgedById: a.acknowledgedById, recoveredAt: a.recoveredAt?.toISOString() ?? null,
      suppressedBy: a.suppressedBy, lastNotifiedAt: a.lastNotifiedAt?.toISOString() ?? null, notifyState: a.notifyState,
    };
  }

  // ================================================================================================ usage
  /** Platform totals and per-organisation billable usage for a range (counts only; no content). */
  @Get("usage")
  @RequireAdminPermission("admin:usage:read")
  async usage(@Query() q: unknown) {
    const { from, to, orgId, limit } = parse(AdminUsageQuery, q);
    const totals = await this.db.$queryRaw<Array<{ key: string; value: bigint }>>`
      SELECT key, sum(value)::bigint AS value FROM admin_v_usage_daily
       WHERE day BETWEEN ${from}::date AND ${to}::date AND (${orgId ?? null}::uuid IS NULL OR org_id = ${orgId ?? null}::uuid) GROUP BY key ORDER BY key`;
    const perOrg = await this.db.$queryRaw<Array<{ org_id: string; name: string | null; key: string; value: bigint }>>`
      WITH t AS (
        SELECT org_id, key, sum(value)::bigint AS value FROM admin_v_usage_daily
         WHERE day BETWEEN ${from}::date AND ${to}::date AND key IN ('http.checks', 'http.inconclusive', 'browser.executions', 'browser.inconclusive',
               'browser.screenshots', 'browser.screenshot_bytes', 'browser.functional_tests', 'deepscan.scans', 'deepscan.pages')
               AND (${orgId ?? null}::uuid IS NULL OR org_id = ${orgId ?? null}::uuid)
         GROUP BY 1, 2
      ), top AS (SELECT org_id FROM t WHERE key IN ('http.checks', 'browser.executions', 'deepscan.pages') GROUP BY 1 ORDER BY sum(value) DESC LIMIT ${limit})
      SELECT t.org_id, o.name, t.key, t.value FROM t JOIN top USING (org_id) LEFT JOIN admin_v_organizations o ON o.id = t.org_id`;
    const sums = Object.fromEntries(totals.map((r) => [r.key, Number(r.value)]));
    const orgs = new Map<string, { orgId: string; name: string | null; sums: Record<string, number> }>();
    for (const r of perOrg) {
      const o = orgs.get(r.org_id) ?? { orgId: r.org_id, name: r.name, sums: {} };
      o.sums[r.key] = Number(r.value);
      orgs.set(r.org_id, o);
    }
    return {
      data: {
        from, to,
        totals: totals.map((r) => ({ key: r.key, value: Number(r.value), ...(usageKeyDef(r.key) ?? { kind: "unknown", unit: "count", label: r.key }) })),
        billable: billableUsage(sums),
        organisations: [...orgs.values()].map((o) => ({ orgId: o.orgId, name: o.name, billable: billableUsage(o.sums), recorded: o.sums })),
        policy: "Work counters are recorded once per logical result (ledger-gated, retry-safe). Inconclusive results are recorded but not billable. Cancelled executions, failed attempts and retries are platform overhead and never billable.",
      },
    };
  }

  @Get("usage/reconciliations")
  @RequireAdminPermission("admin:usage:read")
  async reconciliations() {
    const runs = await this.db.usageReconciliationRun.findMany({ orderBy: { requestedAt: "desc" }, take: 60, include: { _count: { select: { discrepancies: true } } } });
    return { data: runs.map((r) => ({ id: r.id, day: day(r.day), status: r.status, requestedById: r.requestedById, requestedAt: r.requestedAt.toISOString(), startedAt: r.startedAt?.toISOString() ?? null, finishedAt: r.finishedAt?.toISOString() ?? null, stats: r.stats, error: r.error, discrepancies: r._count.discrepancies })) };
  }

  @Get("usage/reconciliations/:runId")
  @RequireAdminPermission("admin:usage:read")
  async reconciliation(@Param("runId") id: string) {
    const runId = parse(Uuid, id);
    const r = await this.db.usageReconciliationRun.findUnique({ where: { id: runId }, include: { discrepancies: { orderBy: [{ status: "asc" }, { orgId: "asc" }], take: 1000 } } });
    if (!r) throw Errors.notFound();
    const names = new Map((await this.db.$queryRaw<Array<{ id: string; name: string }>>`SELECT id, name FROM admin_v_organizations WHERE id = ANY(${[...new Set(r.discrepancies.map((d) => d.orgId))]}::uuid[])`).map((o) => [o.id, o.name]));
    return {
      data: {
        id: r.id, day: day(r.day), status: r.status, stats: r.stats, error: r.error,
        discrepancies: r.discrepancies.map((d) => ({ id: d.id, orgId: d.orgId, orgName: names.get(d.orgId) ?? null, check: d.check, key: d.key, recorded: Number(d.recorded), expected: Number(d.expected), difference: Number(d.recorded - d.expected), status: d.status, resolution: d.resolution, resolvedAt: d.resolvedAt?.toISOString() ?? null })),
      },
    };
  }

  /** Request a reconciliation of one day (the scheduler runs it within a minute). Audited. */
  @Post("usage/reconciliations")
  @HttpCode(202)
  @RequireAdminPermission("admin:usage:read")
  async requestReconciliation(@CurrentAdmin() admin: AdminContext, @Body() body: unknown, @Client() client: ClientInfo) {
    const { day: d, reason } = parse(AdminReconcileInput, body);
    const today = new Date().toISOString().slice(0, 10);
    if (d >= today) throw new z.ZodError([{ code: "custom", path: ["day"], message: "Only finished days (before today, UTC) can be reconciled", input: d }]);
    const run = await this.db.$transaction(async (tx) => {
      const r = await tx.usageReconciliationRun.create({ data: { day: new Date(`${d}T00:00:00Z`), status: "REQUESTED", requestedById: admin.adminId } });
      await this.audit(tx, admin, client, "admin.usage_reconciliation_requested", "usage_reconciliation", r.id, { day: d }, reason);
      return r;
    });
    return { data: { id: run.id, status: run.status } };
  }

  /** Correct a counter. Counter change + adjustment record + discrepancy resolution + audit in ONE transaction. */
  @Post("usage/adjustments")
  @HttpCode(201)
  @RequireAdminPermission("admin:usage:adjust")
  async adjust(@CurrentAdmin() admin: AdminContext, @Body() body: unknown, @Client() client: ClientInfo) {
    const i = parse(AdminAdjustInput, body);
    if (!usageKeyDef(i.key)) throw new z.ZodError([{ code: "custom", path: ["key"], message: "Unknown usage key", input: i.key }]);
    const id = await this.db.$transaction(async (tx) => {
      const [r] = await tx.$queryRaw<Array<{ id: string }>>`
        SELECT ops.apply_usage_adjustment(${i.orgId}::uuid, ${i.day}::date, ${i.key}, ${BigInt(i.delta)}::bigint, ${i.reason}, ${admin.adminId}::uuid, ${i.discrepancyId ?? null}::uuid) AS id`;
      await this.audit(tx, admin, client, "admin.usage_adjusted", "organization", i.orgId, { day: i.day, key: i.key, delta: i.delta, adjustmentId: r!.id, discrepancyId: i.discrepancyId ?? null }, i.reason);
      return r!.id;
    }).catch((e: unknown) => { throw dbError(e); });
    return { data: { id } };
  }

  @Post("usage/discrepancies/:id/accept")
  @HttpCode(200)
  @RequireAdminPermission("admin:usage:adjust")
  async accept(@CurrentAdmin() admin: AdminContext, @Param("id") id: string, @Body() body: unknown, @Client() client: ClientInfo) {
    const discrepancyId = parse(Uuid, id);
    const { reason } = parse(AdminAcceptDiscrepancyInput, body);
    await this.db.$transaction(async (tx) => {
      await tx.$executeRaw`SELECT ops.accept_usage_discrepancy(${discrepancyId}::uuid, ${reason}, ${admin.adminId}::uuid)`;
      await this.audit(tx, admin, client, "admin.usage_discrepancy_accepted", "usage_discrepancy", discrepancyId, { to: "ACCEPTED" }, reason);
    }).catch((e: unknown) => { throw dbError(e); });
    return { data: { id: discrepancyId, status: "ACCEPTED" } };
  }

  @Get("usage/adjustments")
  @RequireAdminPermission("admin:usage:read")
  async adjustments() {
    const rows = await this.db.usageAdjustment.findMany({ orderBy: { createdAt: "desc" }, take: 200 });
    return { data: rows.map((r) => ({ id: r.id, orgId: r.orgId, day: day(r.day), key: r.key, delta: Number(r.delta), reason: r.reason, actorId: r.actorId, discrepancyId: r.discrepancyId, createdAt: r.createdAt.toISOString() })) };
  }

  // ================================================================================================ configuration
  /**
   * Operational configuration by section, with the metadata the console needs: protected (security policy), apply
   * (live / restart), scope (global; per-organisation limits are plan entitlements), current vs default, last change.
   * Changes go through PATCH /settings (validated, combination-checked, audited, hot-reloaded).
   */
  @Get("config")
  @RequireAdminPermission("admin:settings:read")
  async config() {
    const rows = await this.db.platformSetting.findMany();
    const byKey = new Map(rows.map((r) => [r.key, r]));
    const retention = await this.db.$queryRaw<Array<{ parent: string; granularity: string; retain_days: number; floor_days: number }>>`SELECT * FROM ops.retention_view()`;
    return {
      data: {
        sections: OPERATIONAL_SECTIONS.map((section) => ({
          section,
          settings: settingsInSection(section).map((key) => {
            const def = SETTINGS[key];
            const row = byKey.get(key);
            return { key, description: def.description, value: row ? row.value : def.default, defaultValue: def.default, isDefault: !row, version: row?.version ?? null, updatedAt: row?.updatedAt.toISOString() ?? null, ...settingMeta(key) };
          }),
        })),
        retention: retention.map((r) => ({ table: r.parent, granularity: r.granularity, retainDays: r.retain_days, minimumDays: r.floor_days })),
        alertRules: ALERT_RULES,
        notes: [
          "All settings here are global. Per-organisation limits come from plan entitlements and entitlement overrides.",
          "Secrets, database credentials and network policy are deployment configuration (environment, orchestrator) and cannot be changed here.",
        ],
      },
    };
  }

  /** Change how long a partitioned table's history is kept (never below its floor). Audited with before/after. */
  @Put("config/retention/:table")
  @RequireAdminPermission("admin:settings:write")
  async setRetention(@CurrentAdmin() admin: AdminContext, @Param("table") table: string, @Body() body: unknown, @Client() client: ClientInfo) {
    if (!/^[a-z_]{3,40}$/.test(table)) throw Errors.notFound();
    const { days, reason } = parse(AdminRetentionInput, body);
    await this.db.$transaction(async (tx) => {
      const [r] = await tx.$queryRaw<Array<{ before: number }>>`SELECT ops.set_retention(${table}, ${days}::int) AS before`;
      await this.audit(tx, admin, client, "admin.retention_changed", "partition", table, { from: r!.before, to: days }, reason);
    }).catch((e: unknown) => { throw dbError(e); });
    return this.config();
  }

  private async audit(tx: Tx, a: AdminContext, client: ClientInfo, action: string, targetType: string, targetId: string, changes: Record<string, unknown>, reason: string) {
    await tx.auditLog.createMany({
      data: { stream: PLATFORM_STREAM, actorType: "ADMIN", actorId: a.adminId, actorLabel: a.email, action, targetType, targetId, changes: changes as object, reason, ipPrefix: client.ipPrefix, requestId: client.requestId },
    });
  }
}

/** Map validation raised inside the SECURITY DEFINER functions to 400 / 404 / 409 (never leak SQL). */
function dbError(e: unknown): unknown {
  const msg = (e as { meta?: { message?: string }; message?: string })?.meta?.message ?? (e as Error)?.message ?? "";
  const m = /ERROR: ([^\n]+)/.exec(msg)?.[1] ?? msg;
  if (/unknown organisation|unknown table/.test(m)) return Errors.notFound();
  if (/not open/.test(m)) return Errors.conflict(m.replace(/^.*?: /, "").slice(0, 200));
  if (/invalid|required|out of range|negative|must be between/.test(m)) return new z.ZodError([{ code: "custom", path: [], message: m.slice(0, 200), input: null }]);
  return e;
}
